/**
 * Fast lookup map by uppercase ISO country code
 */
export const COUNTRY_BY_CODE: Record<string, Country> = COUNTRIES.reduce((acc, country) => {
  acc[country.code] = country;
  return acc;
}, {} as Record<string, Country>);

/**
 * Fast lookup map by international calling code (e.g. '+91')
 */
export const COUNTRY_BY_CALLING_CODE: Record<string, Country> = COUNTRIES.reduce((acc, country) => {
  if (!acc[country.callingCode]) {
    acc[country.callingCode] = country;
  }
  return acc;
}, {} as Record<string, Country>);

/**
 * Helper to get all countries
 */
export function getAllCountries(): Country[] {
  return COUNTRIES;
}

/**
 * Helper to get a country by its ISO code (case-insensitive)
 */
export function getCountryByCode(code?: string): Country | undefined {
  if (!code) return undefined;
  return COUNTRY_BY_CODE[code.toUpperCase()];
}

/**
 * Alias for getCountryByCode
 */
export function getCountryByIsoCode(isoCode?: string): Country | undefined {
  return getCountryByCode(isoCode);
}

/**
 * Helper to get a country by its calling code (e.g. '+91' or '91')
 */
export function getCountryByCallingCode(callingCode?: string): Country | undefined {
  if (!callingCode) return undefined;
  const digits = callingCode.replace(/\D/g, '');
  const formatted = `+${digits}`;
  return COUNTRY_BY_CALLING_CODE[formatted];
}

/**
 * Helper to get country ISO code from country code or calling code
 */
export function getCountryIsoCode(codeOrCallingCode?: string): string | undefined {
  if (!codeOrCallingCode) return undefined;
  const byCode = getCountryByCode(codeOrCallingCode);
  if (byCode) return byCode.code;
  const byCalling = getCountryByCallingCode(codeOrCallingCode);
  return byCalling?.code;
}

/**
 * Returns minLength, maxLength, mobileLength, and possibleLengths for a country
 */
export function getCountryLengths(countryCode: string): CountryLengths {
  const country = getCountryByCode(countryCode);
  if (country) {
    return {
      minLength: country.minLength,
      maxLength: country.maxLength,
      mobileLength: country.mobileLength || country.maxLength,
      possibleLengths: country.possibleLengths || [country.minLength],
    };
  }
  return {
    minLength: 4,
    maxLength: 15,
    mobileLength: 10,
    possibleLengths: [10],
  };
}

/**
 * Returns minimum valid national phone number length for a country
 */
export function getCountryMinLength(countryCode: string): number {
  return getCountryLengths(countryCode).minLength;
}

/**
 * Returns maximum valid national phone number length for a country
 */
export function getCountryMaxLength(countryCode: string): number {
  return getCountryLengths(countryCode).maxLength;
}
